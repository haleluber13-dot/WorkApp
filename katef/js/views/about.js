async function crisis(main) {
  const orgs = (await loadCurated()).filter((o) => o.phone && (o.type === "hotline" || o.categories?.includes("emergency") || o.categories?.includes("mental")));
  main.innerHTML = `<section class="page narrow">
    <h1>🆘 קווי סיוע וחירום</h1>
    <p class="lead">אם יש סכנת חיים — התקשרו עכשיו ל-<a href="tel:101">101</a> או <a href="tel:100">100</a>. לא צריך להירשם לשום דבר.</p>
    <div class="cards hotlines">
      ${EMERGENCY.map(([t, n]) => `<a class="card hot" href="tel:${n}"><b>${n}</b><span>${esc(t)}</span></a>`).join("")}
    </div>
    <h2 class="sec">עוד קווי תמיכה</h2>
    <div class="cards hotlines">
      ${orgs.map((o) => `<a class="card hot" href="${esc(telHref(o.phone))}"><b dir="ltr">${esc(o.phone)}</b><span>${esc(o.name)}${o.hours ? ` · ${esc(o.hours)}` : ""}</span></a>`).join("")}
    </div>
    <p class="muted small">המספרים נאספו מאתרים רשמיים. <a href="#/orgs?type=hotline">לרשימה המלאה עם קישורים</a></p>
  </section>`;
}
